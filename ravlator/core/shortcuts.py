"""
[FR-23, FR-24] macOS Standalone .app Bundle Generator & Windows Icon Extractor.
Generates clickable macOS application wrappers inside ~/Applications or Desktop.
Decoupled from GUI frameworks.
"""

import os
import plistlib
import shutil
import stat
from pathlib import Path
from typing import Optional

from ravlator.core.config import Config
from ravlator.core.models import BottleConfig, ProgramEntry


class ShortcutManager:
    """Manages the generation of standalone macOS application bundles."""

    @classmethod
    def get_default_applications_dir(cls) -> Path:
        """User Applications directory ~/Applications."""
        app_dir = Path.home() / "Applications"
        app_dir.mkdir(parents=True, exist_ok=True)
        return app_dir

    @classmethod
    def get_desktop_dir(cls) -> Path:
        return Path.home() / "Desktop"

    @classmethod
    def create_macos_app(
        cls,
        bottle: BottleConfig,
        program: ProgramEntry,
        output_dir: Optional[Path] = None,
        custom_name: Optional[str] = None
    ) -> Path:
        """
        [FR-24] Generates a complete macOS .app bundle.
        
        Bundle Structure:
        <AppName>.app/
        └── Contents/
            ├── Info.plist
            ├── MacOS/
            │   └── launcher (Bash script invoking ravlator-cli)
            └── Resources/
                └── icon.icns (or icon.png)
        """
        app_name = custom_name or program.name or Path(program.exe_path).stem
        # Clean app name for filesystem
        safe_name = "".join(c for c in app_name if c.isalnum() or c in (" ", "-", "_")).strip()
        if not safe_name:
            safe_name = "WindowsGame"

        dest_dir = output_dir or cls.get_default_applications_dir()
        bundle_path = dest_dir / f"{safe_name}.app"

        contents_dir = bundle_path / "Contents"
        macos_dir = contents_dir / "MacOS"
        resources_dir = contents_dir / "Resources"

        # Re-create clean bundle skeleton
        if bundle_path.exists():
            shutil.rmtree(bundle_path)
        macos_dir.mkdir(parents=True, exist_ok=True)
        resources_dir.mkdir(parents=True, exist_ok=True)

        # 1. Generate Info.plist
        bundle_id = f"com.ravlator.bottle.{bottle.id}.{program.id}"
        info_plist_data = {
            "CFBundleExecutable": "launcher",
            "CFBundleIdentifier": bundle_id,
            "CFBundleName": safe_name,
            "CFBundleDisplayName": safe_name,
            "CFBundlePackageType": "APPL",
            "CFBundleShortVersionString": "1.0",
            "CFBundleVersion": "1",
            "CFBundleIconFile": "AppIcon",
            "LSMinimumSystemVersion": "14.0",
            "NSHighResolutionCapable": True,
            "LSUIElement": False
        }

        with open(contents_dir / "Info.plist", "wb") as f:
            plistlib.dump(info_plist_data, f)

        # 2. Extract or Copy Icon [FR-23]
        icon_created = False
        if program.icon_path and Path(program.icon_path).exists():
            src_icon = Path(program.icon_path)
            if src_icon.suffix.lower() == ".icns":
                shutil.copyfile(src_icon, resources_dir / "AppIcon.icns")
                icon_created = True
            elif src_icon.suffix.lower() in (".png", ".ico"):
                shutil.copyfile(src_icon, resources_dir / f"AppIcon{src_icon.suffix}")
                icon_created = True

        if not icon_created:
            default_logo = Path(__file__).resolve().parents[2] / "assets" / "logo.png"
            if default_logo.exists():
                shutil.copyfile(default_logo, resources_dir / "AppIcon.png")

        # 3. Generate launcher execution script
        # Finds python virtual environment or system ravlator runner
        python_exec = Path(sys_python := os.environ.get("RAVLATOR_PYTHON_BIN", ""))
        if not python_exec.exists():
            # Detect project .venv or fallback to python3
            local_venv = Path(__file__).resolve().parents[2] / ".venv" / "bin" / "python"
            python_exec = local_venv if local_venv.exists() else Path("/usr/bin/python3")

        cli_module = "ravlator.cli.main"
        project_root = Path(__file__).resolve().parents[2]

        launcher_script = f"""#!/bin/sh
# Auto-generated by Ravlator for bottle '{bottle.name}'
export PYTHONPATH="{project_root}:$PYTHONPATH"
exec "{python_exec}" -m {cli_module} run --bottle "{bottle.id}" --exe "{program.exe_path}" {program.arguments} "$@"
"""

        launcher_path = macos_dir / "launcher"
        with open(launcher_path, "w", encoding="utf-8") as f:
            f.write(launcher_script)

        # Make launcher executable
        launcher_path.chmod(launcher_path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

        return bundle_path
